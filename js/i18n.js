const I18N = {
  lang() { try { return localStorage.getItem(LANG_KEY) || 'en'; } catch (e) { return 'en'; } },
  set(l) { localStorage.setItem(LANG_KEY, l); },
};
/** Translate a UI string (keeps a trailing " *" required marker). */
function t(s) {
  if (s == null) return '';
  const lang = I18N.lang();
  if (lang === 'en') return s;
  const idx = { ms: 0, 'zh-CN': 1, 'zh-TW': 2 }[lang];
  const str = String(s);
  const star = str.endsWith(' *');
  const key = star ? str.slice(0, -2) : str;
  const tr = DICT[key] && DICT[key][idx];
  return tr ? tr + (star ? ' *' : '') : str;
}
